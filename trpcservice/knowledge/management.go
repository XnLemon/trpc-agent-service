type memoryVersionStore struct {
	mu     sync.Mutex
	values map[string][]Version
}

func newMemoryVersionStore() *memoryVersionStore {
	return &memoryVersionStore{values: make(map[string][]Version)}
}

func (store *memoryVersionStore) PublishVersion(ctx context.Context, value Version) (Version, error) {
	if err := validateVersionInput(ctx, value); err != nil {
		return Version{}, err
	}
	store.mu.Lock()
	defer store.mu.Unlock()
	key := value.TenantID + "\x00" + value.AppID
	values := store.values[key]
	for _, existing := range values {
		if existing.ContentDigest == value.ContentDigest {
			return existing, nil
		}
	}
	value.Version = int64(len(values) + 1)
	store.values[key] = append(values, value)
	return value, nil
}

func (store *memoryVersionStore) ListVersions(ctx context.Context, scope Scope) ([]Version, error) {
	if nilvalue.Is(ctx) {
		return nil, ErrInvalid
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if err := scope.Validate(); err != nil {
		return nil, err
	}
	store.mu.Lock()
	defer store.mu.Unlock()
	values := append([]Version(nil), store.values[scope.TenantID+"\x00"+scope.AppID]...)
	for left, right := 0, len(values)-1; left < right; left, right = left+1, right-1 {
		values[left], values[right] = values[right], values[left]
	}
	return values, nil
}

func validateVersionInput(ctx context.Context, value Version) error {
	if nilvalue.Is(ctx) {
		return ErrInvalid
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	if !validScopeID(value.TenantID) || !validScopeID(value.AppID) || value.Version != 0 || value.DocumentCount < 0 || len(value.ContentDigest) != sha256.Size*2 || strings.ToLower(value.ContentDigest) != value.ContentDigest || value.PublishedAt.IsZero() || value.PublishedAt.Location() != time.UTC || value.ActorID != strings.TrimSpace(value.ActorID) || !validText(value.ActorID, 256, true) {
		return ErrInvalid
	}
	if _, err := hex.DecodeString(value.ContentDigest); err != nil {
		return ErrInvalid
	}
	return nil
}

